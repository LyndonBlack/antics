#!/usr/bin/env bash
# export-public.sh -- build the tree that is safe to publish.
#
#   scripts/export-public.sh <target-dir>
#
# Copies ONLY source, manifest, docs, CI, scripts and a .gitignore out of this crate. Everything the
# copyright owner of the original game could object to -- the ten art files regenerated from the
# original in assets/, the recorded sessions, the emulator checkouts, the build output, the private
# hand-test notes -- is left behind, and the result is audited before the script exits successfully.
#
# Refuses to write into an existing non-empty directory, so it can never merge into a tree that
# already holds something.
#
# Exit codes: 0 = exported and audited clean; 1 = refused, or the audit failed (the reason is
# printed). An audit failure means DO NOT PUBLISH the target directory.
set -euo pipefail

die() { printf 'export-public: %s\n' "$*" >&2; exit 1; }

[ $# -ge 1 ] || die "usage: $0 <target-dir>   |   $0 --audit-only <existing-tree>"
AUDIT_ONLY=0
if [ "$1" = "--audit-only" ]; then
    AUDIT_ONLY=1
    [ $# -eq 2 ] || die "usage: $0 --audit-only <existing-tree>"
    shift
fi
TARGET_ARG="$1"

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$(cd "$HERE/.." && pwd)"
if [ "$AUDIT_ONLY" -eq 0 ]; then
    [ -f "$SRC/Cargo.toml" ] || die "$SRC does not look like the port directory (no Cargo.toml)"
    [ -d "$SRC/src" ]        || die "$SRC has no src/"
fi

# --- target directory -----------------------------------------------------------------------
if [ "$AUDIT_ONLY" -eq 0 ]; then
    mkdir -p "$TARGET_ARG"
fi
[ -d "$TARGET_ARG" ] || die "no such directory: $TARGET_ARG"
TARGET="$(cd "$TARGET_ARG" && pwd)"
if [ "$AUDIT_ONLY" -eq 0 ]; then
    [ "$TARGET" != "$SRC" ] || die "target is the crate itself"
    case "$SRC/" in "$TARGET"/*) die "target is a parent of the crate; pick a fresh directory" ;; esac
    if [ -n "$(ls -A "$TARGET")" ]; then
        die "target directory is not empty: $TARGET (give me a fresh directory)"
    fi
fi

# --- what goes in ---------------------------------------------------------------------------
# Files kept by name. Directories kept whole: src/, docs/, scripts/.
KEEP_FILES=(Cargo.toml Cargo.lock README.md LICENSE CHANGELOG.md CONTRIBUTING.md SECURITY.md)
# Paths that must never appear in the result, whatever else happens.
EXCLUDED_DIRS=(assets play recon target .git)
EXCLUDED_FILES=(HAND_TEST_CHECKLIST.md)
EXCLUDED_GLOBS=('*.bin' '*.exe' '*.dat' '*.png' '*.bmp' '*.wav')

if [ "$AUDIT_ONLY" -eq 0 ]; then

printf 'export-public: %s -> %s\n' "$SRC" "$TARGET"

for f in "${KEEP_FILES[@]}"; do
    [ -f "$SRC/$f" ] || die "missing $f in the crate"
    cp -p "$SRC/$f" "$TARGET/$f"
done

for d in src docs scripts; do
    [ -d "$SRC/$d" ] || die "missing $d/ in the crate"
    cp -Rp "$SRC/$d" "$TARGET/$d"
done

# The workflows live in ci/ here (this repo's .github/ belongs to the mono-repo) and become
# .github/workflows/ in the published repository, whose root is this directory.
if [ -d "$SRC/ci" ]; then
    mkdir -p "$TARGET/.github/workflows"
    for wf in "$SRC"/ci/*.yml "$SRC"/ci/*.yaml; do
        [ -f "$wf" ] || continue
        cp -p "$wf" "$TARGET/.github/workflows/$(basename "$wf")"
    done
fi

cat > "$TARGET/.gitignore" <<'GITIGNORE'
# build output
/target/
# original-derived data: regenerated by `antics --install` into the user's data directory,
# never committed here
assets/
*.bin
*.exe
*.dat
*.png
*.bmp
*.wav
# private working material
recon/
play/
HAND_TEST_CHECKLIST.md
.DS_Store
GITIGNORE

fi   # AUDIT_ONLY - 0

# --- audit ----------------------------------------------------------------------------------
# Nothing below is optional: each check exits 1 on the first problem it finds.
printf 'export-public: auditing %s\n' "$TARGET"
fail=0

# 1. excluded directories must not exist at all
for d in "${EXCLUDED_DIRS[@]}"; do
    if [ -e "$TARGET/$d" ]; then
        printf 'AUDIT FAIL: excluded directory present: %s\n' "$d" >&2; fail=1
    fi
done

# 2. excluded file names and extensions, anywhere in the tree
for f in "${EXCLUDED_FILES[@]}"; do
    found="$(find "$TARGET" -name "$f" -print)"
    if [ -n "$found" ]; then printf 'AUDIT FAIL: excluded file present:\n%s\n' "$found" >&2; fail=1; fi
done
for g in "${EXCLUDED_GLOBS[@]}"; do
    found="$(find "$TARGET" -type f -name "$g" -print)"
    if [ -n "$found" ]; then printf 'AUDIT FAIL: excluded pattern %s present:\n%s\n' "$g" "$found" >&2; fail=1; fi
done

# 3. no file larger than 1 MB (the port's sources are ~1.3 MB in total, largest file ~900 KB;
#    anything bigger is data, not code)
big="$(find "$TARGET" -type f -size +1M -print)"
if [ -n "$big" ]; then
    printf 'AUDIT FAIL: file larger than 1 MB:\n' >&2
    find "$TARGET" -type f -size +1M -printf '  %s  %p\n' >&2; fail=1
fi

# 4. no absolute home paths, and no reference to the download site anywhere.
HOME_PAT="$(printf '%s' "$HOME")"
hits="$(grep -rIl -F "$HOME_PAT" "$TARGET" || true)"
if [ -n "$hits" ]; then printf 'AUDIT FAIL: absolute home path in:\n%s\n' "$hits" >&2; fail=1; fi

BAD_SITE="$(printf 'abandon%s' 'ware')"
hits="$(grep -rIl -F "$BAD_SITE" "$TARGET" || true)"
if [ -n "$hits" ]; then
    printf 'AUDIT FAIL: the download site is named:\n%s\n' "$hits" >&2
    fail=1
fi

if [ "$fail" -ne 0 ]; then
    printf 'export-public: AUDIT FAILED -- do not publish %s\n' "$TARGET" >&2
    exit 1
fi

# --- summary --------------------------------------------------------------------------------
printf 'export-public: audit clean\n'
printf 'export-public: %s files, %s\n' \
    "$(find "$TARGET" -type f | wc -l | tr -d ' ')" \
    "$(du -sh "$TARGET" | cut -f1)"
printf 'export-public: largest files:\n'
find "$TARGET" -type f -printf '%s\t%p\n' | sort -rn | head -5 | sed 's/^/  /'
printf 'export-public: next steps in %s:\n' "$TARGET"
printf '  git init && git add -A && git commit -m "antics: engine port, no original data"\n'
printf '  cargo build --release --offline\n'
